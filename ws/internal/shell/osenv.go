package shell

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/igwtcode/workstation/ws/internal/app"
)

type OSEnvArtifact struct {
	Path    string `json:"path"`
	Content string `json:"content"`
	Summary string `json:"summary"`
}

func resolveXDGEnv(ctx *app.Context) [][2]string {
	home := ctx.HomeDir
	cfg := ctx.ConfigDir
	if cfg == "" {
		cfg = filepath.Join(home, ".config")
	}
	data := ctx.DataDir
	if data == "" {
		data = filepath.Join(home, ".local", "share")
	}
	state := ctx.StateDir
	if state == "" {
		state = filepath.Join(home, ".local", "state")
	}
	cache := ctx.CacheDir
	if cache == "" {
		cache = filepath.Join(home, ".cache")
	}
	return [][2]string{
		{"XDG_CONFIG_HOME", cfg},
		{"XDG_DATA_HOME", data},
		{"XDG_STATE_HOME", state},
		{"XDG_CACHE_HOME", cache},
	}
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func xmlEscape(s string) string {
	var buf bytes.Buffer
	_ = xml.EscapeText(&buf, []byte(s))
	return buf.String()
}

func targetOS(ctx *app.Context) string {
	if ctx != nil && ctx.Host.OS != "" {
		return ctx.Host.OS
	}
	return runtime.GOOS
}

func formatSystemdEnvValue(v string) (string, error) {
	if strings.ContainsAny(v, "\n\r\x00") {
		return "", fmt.Errorf("systemd environment value contains invalid control character")
	}
	if strings.ContainsAny(v, " \t\"\\$") {
		escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(v)
		return `"` + escaped + `"`, nil
	}
	return v, nil
}

func RenderOSEnv(ctx *app.Context) (OSEnvArtifact, error) {
	if ctx == nil || ctx.HomeDir == "" {
		return OSEnvArtifact{}, fmt.Errorf("home directory is required")
	}
	osName := targetOS(ctx)
	pairs := resolveXDGEnv(ctx)

	switch osName {
	case "linux":
		cfgDir := ctx.ConfigDir
		if cfgDir == "" {
			cfgDir = filepath.Join(ctx.HomeDir, ".config")
		}
		path := filepath.Join(cfgDir, "environment.d", "ws-xdg.conf")
		var b strings.Builder
		b.WriteString("# Generated by ws os-env\n")
		for _, kv := range pairs {
			val, err := formatSystemdEnvValue(kv[1])
			if err != nil {
				return OSEnvArtifact{}, fmt.Errorf("%s: %w", kv[0], err)
			}
			fmt.Fprintf(&b, "%s=%s\n", kv[0], val)
		}
		return OSEnvArtifact{
			Path:    path,
			Content: b.String(),
			Summary: "Linux systemd environment.d config exporting XDG base directories",
		}, nil

	case "darwin":
		path := filepath.Join(ctx.HomeDir, "Library", "LaunchAgents", "dev.workstation.ws-env.plist")
		cmds := make([]string, 0, len(pairs))
		for _, kv := range pairs {
			cmds = append(cmds, fmt.Sprintf("/bin/launchctl setenv %s %s", kv[0], shellQuote(kv[1])))
		}
		script := strings.Join(cmds, " && ")
		content := fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>dev.workstation.ws-env</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>-c</string>
    <string>%s</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
</dict>
</plist>
`, xmlEscape(script))
		return OSEnvArtifact{
			Path:    path,
			Content: content,
			Summary: "macOS LaunchAgent exporting XDG base directories via launchctl setenv",
		}, nil

	default:
		return OSEnvArtifact{}, fmt.Errorf("unsupported OS %q for os-env", osName)
	}
}

func ApplyOSEnv(ctx *app.Context) error {
	art, err := RenderOSEnv(ctx)
	if err != nil {
		return err
	}
	if ctx.DryRun {
		return nil
	}
	if err := app.WriteAtomicFile(art.Path, []byte(art.Content), 0o644); err != nil {
		return err
	}

	if targetOS(ctx) == "darwin" {
		realHome, err := os.UserHomeDir()
		if err == nil && realHome != "" && filepath.Clean(ctx.HomeDir) == filepath.Clean(realHome) {
			if launchctl, err := exec.LookPath("launchctl"); err == nil {
				for _, kv := range resolveXDGEnv(ctx) {
					if out, err := exec.Command(launchctl, "setenv", kv[0], kv[1]).CombinedOutput(); err != nil {
						return fmt.Errorf("launchctl setenv %s: %w (%s)", kv[0], err, strings.TrimSpace(string(out)))
					}
				}
			}
		}
	}
	return nil
}
